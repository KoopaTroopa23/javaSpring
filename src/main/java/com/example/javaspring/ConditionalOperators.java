package com.example.javaspring;

public class ConditionalOperators {
    public static void main(String[] args) {
      
    // Condition operators   - always returns a boolean value
    int i = 1;
        System.out.println(i < 5);  //  < — less than
        System.out.println(i > 5);  // > — greater than
        System.out.println(i <= 5);  // <= — less than or equal to
        System.out.println(i >= 5);  // >= — greater than or equal to
        System.out.println(i == 5);  //  == — equal to (comparing values — not to be confused with =, which assigns a value)
        
    }
}