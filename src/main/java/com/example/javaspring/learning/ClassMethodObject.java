package com.example.javaspring.learning;

public class ClassMethodObject {
    public static void main(String[] args) {

        System.out.println("Package — the cookbook section, like \"Desserts\".");
        System.out.println("Class — one recipe, like \"Chocolate Cake\".");
        System.out.println("Interface — a contract saying \"any dessert must have a bake() method\", without saying how.");
        System.out.println("Abstract Class — a recipe template that leaves some steps blank; you can't bake from it directly.");
        System.out.println("Inheritance — a \"Birthday Cake\" recipe that reuses a base \"Cake\" recipe's steps, adding its own.");
        System.out.println("Constructor — the process that creates the instance, like baking the cake.");
        System.out.println("Instance — an actual cake baked from that recipe.");
        System.out.println("Field — a property the cake has, like flavor or size.");
        System.out.println("Access Modifier — whether a step is usable by other recipes (public) or hidden inside this one (private).");
        System.out.println("Enum — a fixed list of choices, like cake sizes: SMALL, MEDIUM, LARGE.");
        System.out.println("Method — one step of the recipe, like bake().");
        System.out.println("Polymorphism — different desserts all respond to bake(), but each bakes differently inside.");
        System.out.println("Statement — one instruction inside that step, like \"set oven to 350\".");
        System.out.println("Expression — the value being calculated, like 2 * 1.5 (cups of flour).");

    }
}
